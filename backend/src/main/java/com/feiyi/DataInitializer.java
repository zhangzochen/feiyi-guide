    private Exhibit exhibit(String name, String category, String region, String era, String summary,
                            String description, String highlights, String image, int sort) {
        Exhibit e = new Exhibit();
        e.setName(name);
        e.setCategory(category);
        e.setRegion(region);
        e.setEra(era);
        e.setSummary(summary);
        e.setDescription(description);
        e.setHighlights(highlights);
        e.setImage(image);
        e.setSort(sort);
        return e;
    }

